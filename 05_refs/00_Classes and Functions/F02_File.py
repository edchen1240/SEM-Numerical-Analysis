def only_allow_certain_files(dir_check, file_only=True, list_ext_no_dot=['png', 'jpg', 'jpeg', 'gif'], list_kwd_exclude=[]):
    #[1] List all files and folders in the directory
    list_folder_and_files = os.listdir(dir_check)
    
    #[2] Count folders and optionally raise a warning if file_only is True
    cnt_folder = sum(1 for item in list_folder_and_files if os.path.isdir(os.path.join(dir_check, item)))
    if file_only and cnt_folder > 0:
        print(f'\t-- File only. Please remove {cnt_folder} folders in the directory. (Ignoring folders and keep going.)')
        
        #[3] Filter out only files if file_only is set to True
        list_folder_and_files = [f for f in list_folder_and_files if os.path.isfile(os.path.join(dir_check, f))]
    
    #[4] Create empty lists to store filtered paths and basenames with extensions
    list_path_filtered = []
    list_bsnext_filtered = []
    
    #[5] Loop through each file and filter by extension
    for iter_path in list_folder_and_files:
        bsn_ext = os.path.basename(iter_path)
        bsn, ext = os.path.splitext(bsn_ext)
        ext = ext.lower().strip('.')  # Convert to lowercase and remove the dot for comparison
        
        #[6] Append to filtered lists if the extension matches
        if ext in list_ext_no_dot:
            list_path_filtered.append(os.path.join(dir_check, iter_path))
            list_bsnext_filtered.append(bsn_ext)
    
    #[7] Filter names by keywords to discard (if list_kwd_exclude is not empty).
    if list_kwd_exclude:
        # Apply keyword filtering
        filtered_indices = [
            i for i, file in enumerate(list_bsnext_filtered)
            if not any(keyword in file for keyword in list_kwd_exclude)
        ]
        list_path_filtered = [list_path_filtered[i] for i in filtered_indices]
        list_bsnext_filtered = [list_bsnext_filtered[i] for i in filtered_indices]
    
    #[8] Return the filtered lists
    return list_path_filtered, list_bsnext_filtered






