def check_attributes_of_an_object(obj):
    # Get all attributes and methods of the object
    attributes = dir(obj)
    for attr in attributes:
        try:
            # Attempt to get the value of the attribute
            value = getattr(obj, attr)
            # Check if the attribute is callable (i.e., a method)
            # and skip it to avoid calling functions unintentionally
            if callable(value):
                print(f'{attr}: <method or callable>')
            else:
                print(f'{attr}: {value}')
        except Exception as e:
            # If the attribute couldn't be accessed, print a message
            print(f'{attr}: <could not access, reason: {e}>')
            






def print_variable_sizes(scope_vars, text_note=None):
    """
    Prints the size of all variables in the given scope in a tabular format.
    Args: scope_vars (dict): A dictionary of variables (e.g., locals() or globals()).
    Usage: M1F.print_variable_sizes(locals())
    gc.collect()
    """
    #[1] Create a list to store variable details
    var_data = []
    total_size_bytes = 0

    for var_name, var_value in scope_vars.items():
        try:
            size_in_bytes = sys.getsizeof(var_value)
            size_in_kb = size_in_bytes / 1024
            total_size_bytes += size_in_bytes
            var_data.append({"Variable Name": var_name, 
                             "Size (Bytes)": size_in_bytes, 
                             "Size (KB)": f"{size_in_kb:.2f}"})
        except Exception as e:
            var_data.append({"Variable Name": var_name, 
                             "Size (Bytes)": "Error", 
                             "Size (KB)": str(e)})

    #[2] Add percentage column
    for var in var_data:
        if isinstance(var["Size (Bytes)"], int):  # Ensure it's a valid size
            var["Pct (%)"] = f"{(var['Size (Bytes)'] / total_size_bytes) * 100:.2f}"
        else:
            var["Pct (%)"] = "Error"

    #[3] Convert to a Pandas DataFrame
    df_var_size = pd.DataFrame(var_data)

    #[4] Print the DataFrame as a table
    timestamp = datetime.now().strftime("%Y-%m%d-%H%M%S")
    print(f'\n[print_variable_sizes] {timestamp} {text_note}:')
    print(f'{tabulate(df_var_size, headers="keys", tablefmt="orgtbl")}\nTotal Size (KB): {total_size_bytes / 1024:.2f}\n\n')
    return df_var_size








